import React from 'react';
import { Head } from '@inertiajs/react';
import { Website } from '@/types';
import ThemeToggle from '@/Components/ThemeToggle';
import SectionRenderer from '@/Components/SectionRenderer';
import { Sparkles, Globe } from 'lucide-react';

interface PublicSiteProps {
    website: Website;
}

export default function PublicSite({ website }: PublicSiteProps) {
    const sections = (website.sections || [])
        .filter((s) => s.is_visible)
        .sort((a, b) => a.order - b.order);

    return (
        <div className="min-h-screen bg-white dark:bg-neutral-950 text-neutral-900 dark:text-neutral-100 font-sans transition-colors duration-150">
            <Head>
                <title>{website.title || website.business_name}</title>
                <meta name="description" content={website.tagline || `${website.business_name} official website.`} />
            </Head>

            {/* Public Header / Navigation */}
            <header className="sticky top-0 z-40 bg-white/90 dark:bg-neutral-950/90 backdrop-blur-md border-b border-neutral-200 dark:border-neutral-800">
                <div className="max-w-6xl mx-auto px-6 h-16 flex items-center justify-between">
                    <div className="flex items-center gap-3">
                        <div className="w-7 h-7 bg-neutral-900 dark:bg-white flex items-center justify-center font-mono font-bold text-white dark:text-neutral-900 text-xs">
                            {website.business_name.charAt(0).toUpperCase()}
                        </div>
                        <span className="font-mono text-sm font-bold uppercase tracking-wider text-neutral-900 dark:text-neutral-100">
                            {website.business_name}
                        </span>
                    </div>

                    {/* Nav Links */}
                    <nav className="hidden md:flex items-center gap-6 text-xs font-mono uppercase tracking-wider text-neutral-600 dark:text-neutral-400">
                        {sections
                            .filter((s) => s.type !== 'hero' && s.type !== 'footer')
                            .slice(0, 5)
                            .map((s) => (
                                <a
                                    key={s.id}
                                    href={`#section-${s.type}`}
                                    className="hover:text-neutral-900 dark:hover:text-white transition-colors"
                                >
                                    {s.type}
                                </a>
                            ))}
                        <a
                            href="#section-contact"
                            className="hover:text-neutral-900 dark:hover:text-white transition-colors font-bold"
                        >
                            Contact
                        </a>
                    </nav>

                    <div className="flex items-center gap-3">
                        <ThemeToggle />
                    </div>
                </div>
            </header>

            {/* Render Public Sections */}
            <main>
                {sections.map((section) => (
                    <SectionRenderer
                        key={section.id}
                        section={section}
                        themeSettings={website.theme_settings}
                        businessName={website.business_name}
                    />
                ))}
            </main>

            {/* Discretionary Minimal Swiss Footer Badge */}
            <div className="py-4 border-t border-neutral-200 dark:border-neutral-800 bg-neutral-50 dark:bg-neutral-950 text-center">
                <a
                    href="/"
                    className="inline-flex items-center gap-1.5 text-[10px] font-mono uppercase text-neutral-400 hover:text-neutral-700 dark:hover:text-neutral-200 transition-colors"
                >
                    <Globe className="w-3 h-3" />
                    <span>Generated by AI Builds My Website</span>
                </a>
            </div>
        </div>
    );
}
